"""Build src/data-ta.js from data-capture/ (real, read-only captures of the live AHI tenant)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cap = root / "data-capture"
monthly = json.loads((cap / "transamerica-monthly.json").read_text())
sentiment = json.loads((cap / "transamerica-sentiment.json").read_text())
contacts = json.loads((cap / "transamerica-contacts.json").read_text())

# clean contact rows: [name, title, email, tagged role, sources]
rows = []
for name, title, email, role, src in contacts:
    if role.startswith("- /"):           # card had no display name; AHI showed the email as the name
        name, role = email, ""
    if len(name) <= 3 and name.isupper() and title:   # initials parsed as name (first card)
        name, title = title, ""
    rows.append([name, title, email, role, src])

js = f"""/* data-ta.js: GENERATED by tools/gen-ta.py from data-capture/. Do not edit by hand.
   REAL: read-only from the live AHI tenant (eme21-platform.eusb.sirioncloud.io) on 19 Nov 2026.
   Customer data: keep this repository private. */
const TA_REAL = {{
  monthlyFields: {json.dumps(monthly["fields"])},
  monthly: {json.dumps(monthly["rows"])},
  sentiment: {json.dumps(sentiment["months"], ensure_ascii=False)},
  contacts: {json.dumps(rows, ensure_ascii=False)},
}};
"""
(root / "src" / "data-ta.js").write_text(js)
print("wrote src/data-ta.js:", len(monthly["rows"]), "months,", len(sentiment["months"]), "sentiment months,", len(rows), "contact cards")
